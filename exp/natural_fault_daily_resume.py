#!/usr/bin/env python3
"""Gate 2 multi-day resume runner.

Runs one frozen-schedule epoch when today's UTC date is not yet covered
(or when --force). The target is configurable and defaults to 14 distinct UTC
calendar dates for the Computer Networks recurrence study. Does not rewrite the
frozen schedule.

Examples:
  python3 work/natural_fault_daily_resume.py           # skip if today already present
  python3 work/natural_fault_daily_resume.py --force   # always add one epoch
  python3 work/natural_fault_daily_resume.py --status  # print day/epoch coverage
"""

from __future__ import annotations

