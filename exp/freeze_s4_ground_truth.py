"""Freeze independent protocol-state ground truth for every S4 query block.

The original paired-baseline run evaluated only the subset for which its
single evaluation endpoint happened to answer both historical nonce calls.
This script does not rewrite those raw samples.  It independently obtains
Mailbox.nonce() at h-1 and h from at least two archive-provider organizations,
requires agreement, and writes an immutable block->expected-count map plus a
reanalysis summary covering every saved S4 response.

The freeze is post-hoc with respect to the original S4 request execution and is
therefore labelled as such in both artifacts and the paper.
"""

