#!/usr/bin/env python3
"""Minimal second-protocol portability check for BoundaryGuard (Wormhole).

Self-contained: no imports from the rest of the repo. Run locally, since the
sandbox proxy blocks public RPC endpoints.

What it does, per window of `--width` finalized Ethereum blocks:
  1. boundary  : eth_call Wormhole Core `nextSequence(emitter)` at (start-1) and (end)
                 -> expected number of messages in the window
  2. logs      : eth_getLogs for `LogMessagePublished` from that emitter
  3. audit     : boundary delta == log count ?   (the Eq.(1) test, count form)
  4. injection : drop one returned log and re-run the audit; it must now fail

Step 4 is what makes this a *detection* result rather than only a consistency
check: it shows the Wormhole boundary would catch a silent omission.

Usage:
    python3 wormhole_min_check.py                 # 12 windows, default RPCs
    python3 wormhole_min_check.py --windows 24
    python3 wormhole_min_check.py --rpc https://your-endpoint

Output: data/wormhole_min_check.json
"""

