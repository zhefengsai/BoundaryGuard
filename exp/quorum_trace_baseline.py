#!/usr/bin/env python3
"""Trace-based 2-of-3 quorum baseline on Gate-2 natural-fault replies.

Offline analytic comparison: no live RPCs. For each (epoch, chain, method,
nonce, block) group, a configured three-provider quorum is replayed from
saved replies and compared with always-dual and a protocol-state check.

Quorum policy (Hyperlane-style majority of successful bodies):
  accept the value shared by at least two of the three configured providers;
  disagreement or fewer than two successful replies is not a silent accept.

Completeness is judged against the Gate-2 semantic_match label for known
dispatched messages. Replica agreement on an incomplete body is a silent miss.
"""

