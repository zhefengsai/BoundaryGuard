#!/usr/bin/env python3
"""Gate 3': run official Hyperlane relayer agent against BoundaryGuard proxy.

This harness:
  1. Writes a local proxy config for Optimism (or configurable chain).
  2. Starts BoundaryGuard as a JSON-RPC endpoint.
  3. Launches the unmodified Hyperlane agent Docker image `./relayer` with
     customRpcUrls pointed at the proxy (host.docker.internal).
  4. Records proxy traces and whether the official binary issued eth_getLogs.

Destination delivery still requires a funded signer key. Pass --signer-key or
HYP_DEFAULTSIGNER_KEY. Without funds the agent may index/query via the proxy
but cannot submit Mailbox.process transactions; that limitation is recorded
honestly in the summary.
"""

